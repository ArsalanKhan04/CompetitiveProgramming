vector<Mint> Inv(1, 1);
vector<Mint> Fac(1, 1);

Mint Comb(int n, int r){
  if (r < 0 || r > n)
    return 0;

  while ((int) Fac.size() < n + 1){
    Fac.pb(Fac.back() * (int) Fac.size());
    Inv.pb(1 / Fac.back());
  }
  return Fac[n] * Inv[r] * Inv[n-r];
}


